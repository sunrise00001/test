#!/usr/bin/env python3
"""Fit two static MIT torque models from GRAV2 serial records."""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from datetime import datetime
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent


def read_pairs(path: Path) -> tuple[np.ndarray, np.ndarray, int]:
    grouped: dict[int, dict[str, tuple[np.ndarray, np.ndarray]]] = defaultdict(dict)
    accepted = 0
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        fields = raw.strip().split(",")
        if len(fields) != 10 or fields[:2] != ["GRAV2", "v1"]:
            continue
        try:
            pair_id = int(fields[3])
            direction = fields[4]
            q = np.array([int(fields[6]), int(fields[7])], dtype=float) / 1000.0
            tau = np.array([int(fields[8]), int(fields[9])], dtype=float) / 1000.0
        except ValueError:
            continue
        if direction not in ("F", "R") or not np.isfinite(q).all() or not np.isfinite(tau).all():
            continue
        grouped[pair_id][direction] = (q, tau)
        accepted += 1
    q_pairs, tau_pairs = [], []
    for pair_id in sorted(grouped):
        item = grouped[pair_id]
        if "F" not in item or "R" not in item:
            continue
        qf, tf = item["F"]
        qr, tr = item["R"]
        if np.max(np.abs(qf - qr)) > 0.06:
            continue
        q_pairs.append((qf + qr) * 0.5)
        tau_pairs.append((tf + tr) * 0.5)
    if len(q_pairs) < 21:
        raise ValueError(f"need at least 21 paired poses; got {len(q_pairs)}")
    return np.stack(q_pairs), np.stack(tau_pairs), accepted


def features(q: np.ndarray) -> np.ndarray:
    q1, q2 = q[:, 0], q[:, 1]
    return np.column_stack((np.ones(len(q)), np.sin(q1), np.cos(q1),
                            np.sin(q1 + q2), np.cos(q1 + q2),
                            np.sin(q2), np.cos(q2)))


def fit(phi: np.ndarray, y: np.ndarray) -> np.ndarray:
    ridge = np.diag([0.0] + [1.0e-4] * 6)
    weights = np.ones(len(y))
    coeff = np.zeros((7, 2))
    for _ in range(8):
        sw = np.sqrt(weights)
        a = phi * sw[:, None]
        b = y * sw[:, None]
        coeff = np.linalg.solve(a.T @ a + ridge, a.T @ b)
        residual = np.linalg.norm(phi @ coeff - y, axis=1)
        med = np.median(residual)
        mad = np.median(np.abs(residual - med))
        delta = max(1.5 * 1.4826 * mad, 0.01)
        weights = np.minimum(1.0, delta / np.maximum(residual, 1.0e-9))
    return coeff


def write_model(coeff: np.ndarray, path: Path) -> None:
    rows = []
    for axis in range(2):
        rows.append("    {" + ", ".join(f"{v:.9e}f" for v in coeff[:, axis]) + "}")
    text = '''#include "gravity_model.h"
#include <math.h>

/* Generated by fit_gravity_2axis.py. Inputs rad, outputs Nm.
 * 1, sin(q1), cos(q1), sin(q1+q2), cos(q1+q2), sin(q2), cos(q2). */
static const float coeff[2][7] = {
''' + ",\n".join(rows) + '''
};

void gravity_model_eval(const float q_rad[2], float torque_nm[2])
{
    float f[7];
    unsigned int i, j;
    f[0] = 1.0f;
    f[1] = sinf(q_rad[0]);
    f[2] = cosf(q_rad[0]);
    f[3] = sinf(q_rad[0] + q_rad[1]);
    f[4] = cosf(q_rad[0] + q_rad[1]);
    f[5] = sinf(q_rad[1]);
    f[6] = cosf(q_rad[1]);
    for (i = 0U; i < 2U; ++i) {
        float value = 0.0f;
        for (j = 0U; j < 7U; ++j) value += coeff[i][j] * f[j];
        torque_nm[i] = value;
    }
}
'''
    path.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--log", type=Path, required=True)
    parser.add_argument("--install", action="store_true", help="replace gravity_model.c")
    args = parser.parse_args()
    q, y, accepted = read_pairs(args.log)
    phi = features(q)
    singular = np.linalg.svd(phi, compute_uv=False)
    condition = float(singular[0] / max(singular[-1], 1.0e-12))
    if condition > 1.0e5:
        raise ValueError(f"poorly excited sample set (condition={condition:.1f})")
    coeff = fit(phi, y)
    residual = phi @ coeff - y
    output = HERE / "fits" / datetime.now().strftime("%Y%m%d_%H%M%S")
    output.mkdir(parents=True, exist_ok=False)
    report = {
        "accepted_records": accepted,
        "paired_poses": len(q),
        "condition_number": condition,
        "mae_nm": np.mean(np.abs(residual), axis=0).tolist(),
        "rmse_nm": np.sqrt(np.mean(residual ** 2, axis=0)).tolist(),
        "coefficients_by_axis": coeff.T.tolist(),
        "note": "Metrics are on fit data; validate on independent poses before use.",
    }
    (output / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_model(coeff, output / "gravity_model.c")
    if args.install:
        write_model(coeff, HERE / "gravity_model.c")
    print(json.dumps({"result": str(output), **report}, indent=2))


if __name__ == "__main__":
    main()
